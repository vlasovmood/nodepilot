#!/bin/sh
# Seal the NodePilot master key into TPM 2.0 with systemd-creds (systemd 250+: Ubuntu 24.04+, Debian 12+).
#
# Afterwards the key is no longer stored on disk in plaintext: a stolen disk or VM snapshot cannot be
# decrypted without this TPM. systemd decrypts the key at service start into $CREDENTIALS_DIRECTORY (tmpfs),
# readable only by the panel process.
#
#   sudo ./seal-master-key.sh --backup-to /root/nodepilot-master.key.backup
#       (move the backup off this server: if the TPM or motherboard fails, it is the only way to recover)
#   sudo ./seal-master-key.sh --i-have-a-backup            # backup already made
#   sudo ./seal-master-key.sh --with-key host+tpm2 ...     # also bind to /var/lib/systemd/credential.secret
#   sudo ./seal-master-key.sh --unseal                     # restore the plaintext key file (e.g. before migrating)
set -eu

KEY=/var/lib/nodepilot/master.key
CRED=/etc/nodepilot/master.key.cred
DROPIN_DIR=/etc/systemd/system/nodepilot.service.d
DROPIN="$DROPIN_DIR/master-key.conf"
WITH_KEY=tpm2
BACKUP=""
HAVE_BACKUP=0
MODE=seal

die() { echo "error: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
    case "$1" in
        --backup-to) BACKUP="${2:-}"; shift 2 ;;
        --i-have-a-backup) HAVE_BACKUP=1; shift ;;
        --with-key) WITH_KEY="${2:-}"; shift 2 ;;
        --unseal) MODE=unseal; shift ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) die "unknown option $1" ;;
    esac
done

[ "$(id -u)" -eq 0 ] || die "run as root"
command -v systemd-creds >/dev/null 2>&1 || die "systemd-creds not found (needs systemd 250+)"
SYSTEMD_VERSION=$(systemctl --version | awk 'NR==1 {print $2}')
[ "${SYSTEMD_VERSION%%.*}" -ge 250 ] 2>/dev/null || die "systemd $SYSTEMD_VERSION is too old: LoadCredentialEncrypted needs 250+"
umask 077

if [ "$MODE" = unseal ]; then
    [ -f "$CRED" ] || die "$CRED not found — the key is not sealed"
    systemd-creds decrypt --name=master.key "$CRED" "$KEY.tmp"
    chown nodepilot:nodepilot "$KEY.tmp"
    mv "$KEY.tmp" "$KEY"
    rm -f "$DROPIN"
    systemctl daemon-reload
    systemctl restart nodepilot
    echo "Unsealed: the master key is back in $KEY (plaintext). $CRED is kept; delete it if no longer needed."
    exit 0
fi

[ -f "$KEY" ] || die "$KEY not found (already sealed? see $CRED)"
case "$WITH_KEY" in
    tpm2|host+tpm2) ;;
    *) die "--with-key must be tpm2 or host+tpm2" ;;
esac
if ! systemd-creds has-tpm2 >/dev/null 2>&1; then
    systemd-creds has-tpm2 || true
    die "no usable TPM 2.0 on this machine (for VMs enable a virtual TPM: vTPM / swtpm)"
fi

if [ -n "$BACKUP" ]; then
    [ -e "$BACKUP" ] && die "$BACKUP already exists"
    cp "$KEY" "$BACKUP"
    chmod 0400 "$BACKUP"
    echo "Backup written to $BACKUP — move it OFF this server (password manager, offline storage) and delete it here."
elif [ "$HAVE_BACKUP" -ne 1 ]; then
    die "make an offline backup of the master key first: --backup-to <file>, or confirm with --i-have-a-backup"
fi

install -d -m 0755 /etc/nodepilot
systemd-creds encrypt --with-key="$WITH_KEY" --name=master.key "$KEY" "$CRED"
chmod 0600 "$CRED"

# Verify decryption works before touching the plaintext copy.
systemd-creds decrypt --name=master.key "$CRED" - | cmp -s - "$KEY" || die "verification failed: the sealed credential does not decrypt to the same key"

install -d -m 0755 "$DROPIN_DIR"
cat > "$DROPIN" <<EOF
# Generated by seal-master-key.sh: the TPM decrypts the master key when the service starts.
[Service]
LoadCredentialEncrypted=master.key:$CRED
EOF
systemctl daemon-reload
systemctl restart nodepilot
sleep 3
systemctl is-active --quiet nodepilot || die "nodepilot failed to start with the sealed key; plaintext key kept at $KEY (journalctl -u nodepilot)"

if command -v shred >/dev/null 2>&1; then shred -u "$KEY"; else rm -f "$KEY"; fi
echo
echo "Sealed with $WITH_KEY. The plaintext key was removed from $KEY."
echo "The panel now reads the key from the systemd credential (Settings → Security shows the source)."
echo "Moving to another machine: unseal first (--unseal) or restore from your offline backup."
